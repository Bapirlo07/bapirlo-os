#!/usr/bin/env python3
"""Bapirlo OS login (slick-greeter) v2 -> ~/bapirlo-os/build/lightdm-v2  (no root).

login.png is the Plymouth background minus the lockup, so Plymouth -> greeter is one
continuous picture: the logo fades away and the login box appears in the same pool.
gtk.css is installed as the lightdm user's GTK user stylesheet (priority beats the
greeter's built-in CSS) to colour the entry, menubar and buttons from the palette.
"""
import os, sys
from PIL import Image
sys.path.insert(0, os.path.dirname(__file__))
from palette import PAL

HOME = os.path.expanduser("~")
OUT = f"{HOME}/bapirlo-os/build/lightdm-v2"
os.makedirs(OUT, exist_ok=True)
Image.open(f"{HOME}/bapirlo-os/build/plymouth-v2/bapirlo/bg.png").convert("RGB").save(f"{OUT}/login.png", optimize=True)
# small lockup badge for slick-greeter's bottom-left "logo" slot
lk = Image.open(f"{HOME}/bapirlo-os/build/plymouth-v2/bapirlo/lockup.png")
lk.resize((lk.width * 150 // lk.height, 150), Image.LANCZOS).save(f"{OUT}/badge.png")

P = PAL
css = f"""/* Bapirlo OS "Kuro" — slick-greeter overrides (generated by tools/build-lightdm-v2.py) */
* {{ font-family: "Inter"; }}

/* top menubar: ink glass, crimson hover */
menubar {{
  background-color: alpha({P['ink']}, 0.55);
  border-bottom: 1px solid alpha({P['crimson']}, 0.35);
  color: {P['paper']};
  padding: 2px 6px;
}}
menubar > menuitem {{ color: {P['mist']}; padding: 4px 10px; border-radius: 8px; }}
menubar > menuitem:hover {{ background-color: alpha({P['crimson']}, 0.30); color: #ffffff; }}
menu, .menu {{ background-color: {P['night']}; color: {P['paper']}; border: 1px solid {P['line']}; border-radius: 12px; padding: 6px; }}
menu menuitem:hover {{ background-color: {P['crimson']}; color: #ffffff; border-radius: 8px; }}

/* password / username field */
entry {{
  background-color: alpha({P['ink']}, 0.78);
  color: {P['paper']};
  caret-color: {P['ember']};
  border: 1px solid {P['line']};
  border-radius: 12px;
  padding: 6px 12px;
  box-shadow: none;
  transition: border-color 200ms ease, box-shadow 200ms ease;
}}
entry:focus {{
  border-color: {P['crimson']};
  box-shadow: 0 0 0 3px alpha({P['crimson']}, 0.30);
}}
entry selection {{ background-color: {P['crimson']}; color: #ffffff; }}
entry image {{ color: {P['crimson']}; }}

button {{
  background-image: none;
  background-color: alpha({P['surface']}, 0.85);
  color: {P['paper']};
  border: 1px solid {P['line']};
  border-radius: 10px;
  transition: background-color 180ms ease;
}}
button:hover {{ background-color: {P['crimson']}; border-color: {P['ember']}; color: #ffffff; }}
button:active {{ background-color: {P['blood']}; }}

label {{ color: {P['paper']}; }}
.prompt-box-is-error label, label.error {{ color: {P['ember']}; }}
"""
open(f"{OUT}/gtk.css", "w").write(css)

conf = f"""# Bapirlo OS login screen — "Kuro" (generated by tools/build-lightdm-v2.py)
[Greeter]
background=/usr/share/backgrounds/bapirlo/login-kuro.png
background-color={P['ink']}
draw-user-backgrounds=false
draw-grid=false
content-align=left
logo=/usr/share/backgrounds/bapirlo/badge-kuro.png
theme-name=WhiteSur-Dark-red
icon-theme-name=Bapirlo
cursor-theme-name=WhiteSur-cursors
cursor-theme-size=24
font-name=Inter Medium 11
enable-hidpi=auto
show-hostname=false
show-clock=true
clock-format=%H:%M  ·  %a %d %b
show-a11y=true
show-keyboard=true
show-power=true
show-quit=true
"""
open(f"{OUT}/slick-greeter.conf", "w").write(conf)
print("LightDM v2 built in", OUT)

# LightDM display-setup-script: the greeter's X server only drives the Intel panel by itself,
# so the monitor on the NVIDIA GPU (HDMI) stays dark/frozen at login. Link NVIDIA as a
# reverse-PRIME output sink, then lay screens out like GNOME does: panel primary at 0,0,
# every other screen at its native mode to the right. Logs to /var/log/bapirlo-displays.log.
# Must always exit 0 — a failing display-setup-script stops LightDM from starting the greeter.
disp = r"""#!/bin/sh
# Bapirlo OS — LightDM display-setup-script (generated by tools/build-lightdm-v2.py)
exec >/var/log/bapirlo-displays.log 2>&1
date
# LightDM should export DISPLAY/XAUTHORITY here, but on this box it arrived empty
# ("Can't open display"), so fall back to the greeter's own X server and cookie.
echo "env: DISPLAY='${DISPLAY:-}' XAUTHORITY='${XAUTHORITY:-}'"
[ -n "${DISPLAY:-}" ] || DISPLAY=:0
if [ -z "${XAUTHORITY:-}" ] || [ ! -r "$XAUTHORITY" ]; then
  for a in "/run/lightdm/root/$DISPLAY" /var/run/lightdm/root/"$DISPLAY"; do
    [ -r "$a" ] && { XAUTHORITY=$a; break; }
  done
fi
export DISPLAY XAUTHORITY
echo "using: DISPLAY=$DISPLAY XAUTHORITY=${XAUTHORITY:-none}"
# the X server can still be coming up — wait up to ~5 s for it to answer
i=0; until xrandr -q >/dev/null 2>&1 || [ $i -ge 25 ]; do sleep 0.2; i=$((i + 1)); done
xrandr --listproviders
src=$(xrandr --listproviders | awk '/modesetting/ {print $4; exit}' | tr -d ,)
for sink in $(xrandr --listproviders | awk '/NVIDIA/ {print $4}' | tr -d ,); do
  [ -n "$src" ] && xrandr --setprovideroutputsource "$sink" "$src"
done
xrandr --auto
panel=$(xrandr | awk '/^eDP[^ ]* connected/ {print $1; exit}')
[ -n "$panel" ] || panel=$(xrandr | awk '/ connected/ {print $1; exit}')
if [ -n "$panel" ]; then
  xrandr --output "$panel" --auto --primary --pos 0x0
  prev=$panel
  for o in $(xrandr | awk -v p="$panel" '/ connected/ && $1 != p {print $1}'); do
    xrandr --output "$o" --auto --right-of "$prev" && prev=$o
  done
fi
xrandr
# round 8: the login screen uses the Bapirlo cursor too (web-greeter's Qt and the Xgreeter wrapper's
# xsetroot read these X resources). Skipped when the theme is not installed system-wide.
if [ -d /usr/share/icons/Bapirlo-Cursors/cursors ]; then
  printf 'Xcursor.theme: Bapirlo-Cursors\nXcursor.size: 32\n' | xrdb -merge && echo "cursor: Bapirlo-Cursors"
fi
exit 0
"""
open(f"{OUT}/bapirlo-displays.sh", "w").write(disp)
os.chmod(f"{OUT}/bapirlo-displays.sh", 0o755)
