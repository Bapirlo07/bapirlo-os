#!/usr/bin/env python3
"""Bapirlo OS desktop v2 "Kuro" -> ~/bapirlo-os/build/desktop-v2 (no root, nothing applied).

  shell/Bapirlo-Kuro/gnome-shell/gnome-shell.css   floating glass top bar (imports WhiteSur)
  ptyxis/bapirlo-kuro.palette                       terminal colours
  fastfetch/config.jsonc + bapirlo-logo.ans         recoloured to the palette
Apply with 60-desktop-v2.sh.
"""
import json, os, re, subprocess, sys
from PIL import Image
sys.path.insert(0, os.path.dirname(__file__))
from palette import PAL, rgb

HOME = os.path.expanduser("~")
OUT = f"{HOME}/bapirlo-os/build/desktop-v2"
P = PAL
def rgba(name, a): r, g, b = rgb(name); return f"rgba({r}, {g}, {b}, {a})"
def ansi(name): r, g, b = rgb(name); return f"38;2;{r};{g};{b}"

# ------------------------------------------------------------------ shell theme
sdir = f"{OUT}/shell/Bapirlo-Kuro/gnome-shell"
os.makedirs(sdir, exist_ok=True)
css = f"""/* Bapirlo OS "Kuro" shell theme — generated by tools/build-desktop-v2.py
   Base: WhiteSur-Dark-red. Only the top bar + a few accents are overridden here. */
@import url("@HOME@/.themes/WhiteSur-Dark-red/gnome-shell/gnome-shell.css");   /* home path filled in on install */

/* ---------- floating bar: inset from the screen edges, rounded, ink glass ---------- */
#panelBox {{
  padding: 8px 12px 0 12px;
}}
#panel {{
  height: 34px !important;
  border-radius: 14px;
  background-color: {rgba('ink', 0.55)};
  border: 1px solid {rgba('crimson', 0.30)};
  box-shadow: 0 6px 18px rgba(0, 0, 0, 0.45);
  font-family: "Inter", sans-serif;
  font-weight: 600;
  color: {P['paper']};
  transition-duration: 300ms;
}}
/* overview & lock screen: drop the glass so the bar melts into the background */
#panel:overview, #panel.unlock-screen, #panel.login-screen {{
  background-color: transparent;
  border-color: transparent;
  box-shadow: none;
}}

/* ---------- buttons: soft pill, crimson wash on hover, solid crimson when pressed ---------- */
#panel .panel-button {{
  color: {P['paper']};
  border-radius: 10px;
  border: 0;
  margin: 3px 1px;
  -natural-hpadding: 12px;
  -minimum-hpadding: 8px;
  box-shadow: inset 0 0 0 100px transparent;
  transition-duration: 220ms;
}}
#panel .panel-button:hover, #panel .panel-button:focus {{
  color: #ffffff;
  box-shadow: inset 0 0 0 100px {rgba('crimson', 0.22)};
}}
#panel .panel-button:active, #panel .panel-button:checked {{
  color: #ffffff;
  box-shadow: inset 0 0 0 100px {rgba('crimson', 0.60)}, 0 0 12px {rgba('crimson', 0.45)};
}}
#panel .panel-button:active:hover, #panel .panel-button:checked:hover {{
  box-shadow: inset 0 0 0 100px {rgba('ember', 0.70)}, 0 0 14px {rgba('ember', 0.50)};
}}

/* ---------- ArcMenu (Bapirlo logo) button: crimson glyph, glows on hover ---------- */
#panel .arcmenu-menu-button StIcon, #panel .panel-button .arcmenu-menu-button {{
  color: {P['crimson']};
}}
#panel .panel-button:hover .arcmenu-menu-button StIcon {{ color: #ffffff; }}

/* ---------- workspace indicator: sakura dots, active one stretches into a crimson pill ---------- */
#panel .panel-button#panelActivities StBoxLayout {{ spacing: 6px; padding: 0 4px; }}
#panel .panel-button#panelActivities .workspace-dot {{
  background-color: {P['crimson']};
  min-width: 7px;
  min-height: 7px;
  border-radius: 99px;
  box-shadow: 0 0 6px {rgba('crimson', 0.55)};
}}

/* ---------- clock: tabular figures in a hairline crimson capsule ---------- */
#panel .panel-button.clock-display .clock {{
  font-feature-settings: "tnum";
  font-weight: 700;
  color: {P['paper']};
  padding: 0 12px;
  border-radius: 9px;
  border: 1px solid {rgba('crimson', 0.40)};
  background-color: {rgba('crimson', 0.12)};
  transition-duration: 220ms;
}}
#panel .panel-button.clock-display:hover .clock {{
  background-color: {rgba('crimson', 0.30)};
  border-color: {rgba('ember', 0.80)};
  box-shadow: none;
}}
#panel .panel-button.clock-display:active .clock, #panel .panel-button.clock-display:checked .clock {{
  background-color: {P['crimson']};
  border-color: {P['ember']};
  color: #ffffff;
  box-shadow: none;
}}
#panel .panel-button.clock-display .messages-indicator {{ color: {P['ember']}; }}

/* status icons */
#panel .panel-button .system-status-icon {{ color: {P['paper']}; }}
#panel .screencast-indicator, #panel .remote-access-indicator {{ color: {P['ember']}; }}

/* ---------- popovers (calendar, quick settings) in the same ink glass ---------- */
.popup-menu-boxpointer .popup-menu-content, .candidate-popup-content {{
  background-color: {rgba('night', 0.94)};
  border: 1px solid {rgba('crimson', 0.25)};
  border-radius: 18px;
  box-shadow: 0 10px 30px rgba(0, 0, 0, 0.55);
}}
.popup-menu-item:hover, .popup-menu-item:focus {{ background-color: {rgba('crimson', 0.22)}; }}
.popup-menu-item:active, .popup-menu-item:checked {{ background-color: {rgba('crimson', 0.45)}; }}
.quick-toggle:checked, .quick-menu-toggle .quick-toggle:checked {{
  background-color: {P['crimson']};
  color: #ffffff;
}}
.quick-toggle:checked:hover {{ background-color: {P['ember']}; }}
.slider {{ -barlevel-active-background-color: {P['crimson']}; color: {P['paper']}; }}
.calendar .calendar-today, .calendar .calendar-today:selected {{ background-color: {P['crimson']}; color: #ffffff; }}
.calendar .calendar-day:selected {{ background-color: {rgba('crimson', 0.35)}; }}
.toggle-switch:checked {{ background-color: {P['crimson']}; }}

/* overview search / selection accents */
.search-entry:focus {{ border-color: {P['crimson']}; box-shadow: inset 0 0 0 1px {P['crimson']}; }}
.app-well-app.app-folder:hover, .overview-tile:hover, .grid-search-result:hover {{ background-color: {rgba('crimson', 0.18)}; }}
"""
open(f"{sdir}/gnome-shell.css", "w").write(css)

# ------------------------------------------------------------------ Ptyxis palette
os.makedirs(f"{OUT}/ptyxis", exist_ok=True)
term = {
    "Background": P["ink"], "Foreground": P["paper"], "Cursor": P["ember"],
    "Color0": "#1C1418", "Color1": P["crimson"], "Color2": P["jade"], "Color3": P["amber"],
    "Color4": P["steel"], "Color5": P["sakura"], "Color6": "#6FC7C2", "Color7": P["mist"],
    "Color8": P["line"], "Color9": P["ember"], "Color10": "#6EE0B4", "Color11": "#FFD08A",
    "Color12": "#A3B8FF", "Color13": "#FFB3C6", "Color14": "#9EE6E1", "Color15": "#FFFFFF",
}
pal = "[Palette]\nName=Bapirlo Kuro\n" + "".join(f"{k}={v}\n" for k, v in term.items())
open(f"{OUT}/ptyxis/bapirlo-kuro.palette", "w").write(pal)

# ------------------------------------------------------------------ fastfetch
os.makedirs(f"{OUT}/fastfetch", exist_ok=True)
tmp = f"{OUT}/fastfetch/_logo.png"
subprocess.run(["rsvg-convert", "-w", "68", "-h", "68", f"{HOME}/bapirlo-os/build/art/logo-kuro.svg", "-o", tmp], check=True)
im = Image.open(tmp).convert("RGBA").resize((34, 34), Image.LANCZOS); os.remove(tmp)
lines = []
for y in range(0, 34, 2):
    row = ""
    for x in range(34):
        t, b = im.getpixel((x, y)), im.getpixel((x, y + 1))
        ton, bon = t[3] > 90, b[3] > 90
        if ton and bon:   row += f"\x1b[38;2;{b[0]};{b[1]};{b[2]};48;2;{t[0]};{t[1]};{t[2]}m▄\x1b[0m"
        elif bon:         row += f"\x1b[38;2;{b[0]};{b[1]};{b[2]}m▄\x1b[0m"
        elif ton:         row += f"\x1b[38;2;{t[0]};{t[1]};{t[2]}m▀\x1b[0m"
        else:             row += " "
    lines.append(row)
open(f"{OUT}/fastfetch/bapirlo-logo.ans", "w").write("\n".join(lines) + "\n")

src = open(f"{HOME}/.config/fastfetch/config.jsonc").read()
cfg = json.loads(re.sub(r"^\s*//.*$", "", src, flags=re.M))
cfg["display"]["color"] = {"keys": ansi("crimson"), "title": ansi("sakura"), "output": ansi("paper")}
E = "\u001b"
cfg["modules"][0] = {"type": "custom", "format":
    f"{E}[1;{ansi('crimson')}mB A P I R L O   O S{E}[0m  {E}[{ansi('muted')}m// kuro edition{E}[0m"}
cfg["modules"][2] = {"type": "custom", "format":
    f"{E}[{ansi('blood')}m━━━━━━{E}[{ansi('crimson')}m━━━━━━{E}[{ansi('ember')}m━━━━━━{E}[{ansi('sakura')}m━━━━━━{E}[0m"}
for m in cfg["modules"]:
    if isinstance(m, dict) and "keyColor" in m:
        m["keyColor"] = ansi("sakura")
out = "// Bapirlo OS — fastfetch (\"Kuro\" palette; generated by tools/build-desktop-v2.py)\n" + json.dumps(cfg, indent=2, ensure_ascii=False) + "\n"
open(f"{OUT}/fastfetch/config.jsonc", "w").write(out)
print("desktop v2 built in", OUT)
