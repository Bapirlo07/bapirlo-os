#!/usr/bin/env python3
"""Bapirlo OS — colour the Hyprland session from Theme Studio's palette.

Writes (all generated, safe to delete):
  ~/.config/hypr/bapirlo-colors.conf   Hyprland $variables (legacy .conf)
  ~/.config/hypr/bapirlo-colors.lua    colours for hyprland.lua
  ~/.config/hypr/hyprlock.conf         lock screen (wallpaper still + clock)
  ~/.config/waybar/style.css           bar
  ~/.config/fuzzel/fuzzel.ini          launcher
  ~/.config/mako/config                notifications
Run by 1510-hyprland.sh and by Theme Studio after every re-theme; reloads whatever is running.
"""
import json
import os
import shutil
import subprocess

HOME = os.path.expanduser("~")
CONF = os.environ.get("XDG_CONFIG_HOME", os.path.join(HOME, ".config"))
STATE = os.environ.get("XDG_STATE_HOME", os.path.join(HOME, ".local", "state"))
ACTIVE = os.path.join(STATE, "bapirlo", "studio", "active.json")
WALL_STATE = os.path.join(STATE, "bapirlo", "wallpaper", "current.json")

# Original Kuro palette (tools/palette.py) when Theme Studio has nothing active
KURO = {"ink": "#0E0A0D", "night": "#181014", "surface": "#251A1F", "line": "#543B45", "muted": "#917682",
        "mist": "#CDB5BE", "paper": "#F2E9EC", "crimson": "#E11D2E", "ember": "#FF4655", "blood": "#7C061F",
        "sakura": "#F08AA4", "jade": "#3FC69A", "amber": "#F2B45A"}


def palette():
    try:
        with open(ACTIVE) as f:
            return {**KURO, **json.load(f).get("palette", {})}
    except (OSError, ValueError):
        return dict(KURO)


def rgba(hexc, alpha):
    h = hexc.lstrip("#")
    return f"rgba({int(h[0:2], 16)}, {int(h[2:4], 16)}, {int(h[4:6], 16)}, {alpha})"


def hypr(hexc, alpha="ff"):
    return f"rgba({hexc.lstrip('#').lower()}{alpha})"


def still():
    try:
        with open(WALL_STATE) as f:
            s = json.load(f)
        return s.get("still") or s.get("path") or ""
    except (OSError, ValueError):
        return ""


def write(path, text):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    tmp = path + ".tmp"
    with open(tmp, "w") as f:
        f.write(text)
    os.replace(tmp, path)


def colors_conf(p):
    names = ["ink", "night", "surface", "line", "muted", "mist", "paper", "crimson", "ember", "blood", "sakura"]
    lines = ["# generated by tools/hypr-theme.py from Theme Studio — do not edit"]
    lines += [f"${n} = {hypr(p[n])}" for n in names]
    lines.append(f"$shadow = {hypr(p['ink'], 'cc')}")
    return "\n".join(lines) + "\n"


def colors_lua(p):
    names = ["ink", "night", "surface", "line", "muted", "mist", "paper", "crimson", "ember", "blood", "sakura"]
    lines = ["-- generated by tools/hypr-theme.py from Theme Studio — do not edit", "return {"]
    lines += [f'    {n} = "{hypr(p[n])}",' for n in names]
    lines += [f'    shadow = "{hypr(p["ink"], "cc")}",', "}"]
    return "\n".join(lines) + "\n"


