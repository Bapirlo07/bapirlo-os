def reload():
    def run(*cmd):
        if shutil.which(cmd[0]):
            subprocess.run(cmd, capture_output=True)
    if not os.environ.get("HYPRLAND_INSTANCE_SIGNATURE"):
        return
    run("hyprctl", "reload")
    run("makoctl", "reload")
    run("pkill", "-SIGUSR2", "-x", "waybar")   # waybar re-reads style.css


def main():
    p = palette()
    write(os.path.join(CONF, "hypr", "bapirlo-colors.conf"), colors_conf(p))
    write(os.path.join(CONF, "hypr", "bapirlo-colors.lua"), colors_lua(p))
    write(os.path.join(CONF, "hypr", "hyprlock.conf"), hyprlock_conf(p))
    write(os.path.join(CONF, "waybar", "style.css"), waybar_css(p))
    write(os.path.join(CONF, "fuzzel", "fuzzel.ini"), fuzzel_ini(p))
    write(os.path.join(CONF, "mako", "config"), mako_conf(p))
    reload()


if __name__ == "__main__":
    main()
