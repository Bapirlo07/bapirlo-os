#!/usr/bin/env bash
# Bapirlo OS installer — rebuild the whole "Kuro" desktop on a fresh CachyOS GNOME install.
#
#   ./install.sh --wallpaper ~/Pictures/my-art.jpg [options]
#
#   --wallpaper PATH   the picture the theme is built around (REQUIRED — the original art is
#                      third-party fan art and is not shipped in this repo)
#   --city NAME --lat N --lon N
#                      weather / sunrise location (stored in ~/.config/bapirlo/location.json only)
#   --boot             also theme GRUB + Plymouth + LightDM (machine-specific: read 50-boot-v2.sh first)
#   --dry-run          print every step, change nothing
#   --yes              don't pause between phases
#
# Phases (each step is one of the numbered scripts; every one of them backs up first into
# ~/theme-backups and has its own `restore`):
#   1 checks             CachyOS + GNOME 50, run as your user, paru present
#   2 safety             Timeshift configured (05-timeshift.sh) + snapshot "Before Bapirlo OS"
#   3 packages           base packages (pacman) · then 130 / 200 / 300 install steps: each shows its
#                        packages; AUR packages go through paru as YOU, which shows every PKGBUILD
#   4 upstream themes    WhiteSur GTK / icons / cursors at pinned commits + the Kuro colour patch
#   5 art                fonts, your wallpaper → upscaled hero, blurred copies, day/night grades,
#                        boot / login art and the shell theme are generated by tools/*.py
#   6 extensions         the ones from extensions.gnome.org that the scripts expect
#   7 desktop            10 → 60 → 70 → 80 … 310 (no sudo)
#   8 boot (--boot only) 50-boot-v2.sh + 55-grub-tune.sh (GRUB, Plymouth, LightDM)
# Never touches partitions, fstab or the EFI partition.
set -euo pipefail
HERE=$(cd "$(dirname "$(readlink -f "$0")")" && pwd)
WALL="" CITY="" LAT="" LON="" BOOT=0 DRY=0 YES=0
while [ $# -gt 0 ]; do
  case $1 in
    --wallpaper) WALL=$2; shift ;;
    --city) CITY=$2; shift ;; --lat) LAT=$2; shift ;; --lon) LON=$2; shift ;;
    --boot) BOOT=1 ;; --dry-run) DRY=1 ;; --yes) YES=1 ;;
    -h|--help) sed -n 2,28p "$0"; exit 0 ;;
    *) echo "unknown option $1"; exit 1 ;;
  esac; shift
done

R=$'\e[38;2;255;70;85m' D=$'\e[38;2;202;181;191m' B=$'\e[1m' N=$'\e[0m'
phase() { printf '\n%s%s== %s%s\n' "$B" "$R" "$*" "$N"; [ $YES = 1 ] || [ $DRY = 1 ] || { read -rp "${D}continue? [Y/n] ${N}" a; [[ ${a:-y} =~ ^[Yy] ]] || exit 1; }; }
run() { printf '%s  $ %s%s\n' "$D" "$*" "$N"; [ $DRY = 1 ] || "$@"; }
export BAPIRLO_INSTALLER=1

# pinned upstream versions (the exact commits Bapirlo OS was built and tested with)
declare -A WHITESUR=(
  [WhiteSur-gtk-theme]=d578265  [WhiteSur-icon-theme]=73d8040  [WhiteSur-cursors]=e190baf )
BASE_PKGS=(paru git extension-manager gnome-shell-extensions gnome-shell-extension-arc-menu
  gnome-shell-extension-appindicator inter-font ttf-jetbrains-mono-nerd papirus-icon-theme
  sassc libxml2 python-pillow librsvg alacritty fastfetch vte4 timeshift cronie ufw
  pacman-contrib power-profiles-daemon)
# extensions installed by hand in round 1 (the later scripts install their own)
ROUND1_EXTS=(blur-my-shell@aunetx burn-my-windows@schneegans.github.com
  compiz-alike-magic-lamp-effect@hermes83.github.com dash2dock-lite@icedman.github.com)

# ------------------------------------------------------------------ 1 checks
phase "1/8 checks"
[ "$(id -u)" -ne 0 ] || { echo "Run as your normal user (it asks for sudo when needed)."; exit 1; }
grep -qi cachyos /etc/os-release || echo "!! not CachyOS — continuing, but only CachyOS GNOME was tested"
GV=$(gnome-shell --version | grep -oE '[0-9]+' | head -1)
[ "$GV" = 50 ] || { echo "!! GNOME $GV found; Bapirlo OS targets GNOME 50 (extensions are pinned to it)"; exit 1; }
[ -n "$WALL" ] && [ -f "$WALL" ] || { echo "--wallpaper PATH is required (an image file)"; exit 1; }
[ "$HERE" = "$HOME/bapirlo-os" ] || { echo "Clone the repo to ~/bapirlo-os (the builders expect that path)."; exit 1; }
DM=$(basename "$(readlink -f /etc/systemd/system/display-manager.service 2>/dev/null)" .service)
echo "GNOME $GV · display manager: ${DM:-none} · $(cat /sys/class/dmi/id/sys_vendor 2>/dev/null)"
[ "$DM" = lightdm ] || echo "   (not LightDM: the themed login screen and LightDM lock are skipped; GNOME's lock is used)"

# ------------------------------------------------------------------ 2 safety
phase "2/8 Timeshift + snapshot \"Before Bapirlo OS\""
run sudo pacman -S --needed timeshift cronie
if [ $DRY = 1 ] || ! sudo test -s /etc/timeshift/timeshift.json; then run sudo bash "$HERE/05-timeshift.sh"; fi
if [ $DRY = 0 ] && ! sudo timeshift --list --scripted 2>/dev/null | grep -q "Before Bapirlo OS"; then
  run sudo timeshift --create --scripted --comments "Before Bapirlo OS" --tags O
fi

# ------------------------------------------------------------------ 3 packages
phase "3/8 packages (pacman, then the AUR through paru — review each PKGBUILD)"
run sudo pacman -S --needed "${BASE_PKGS[@]}"
run bash "$HERE/130-install-step.sh"
run bash "$HERE/200-round2-install.sh"
run bash "$HERE/300-round3-install.sh"

# ------------------------------------------------------------------ 4 upstream themes
phase "4/8 WhiteSur GTK / icons / cursors (pinned) + Kuro colour patch"
mkdir -p "$HERE/src"
for repo in "${!WHITESUR[@]}"; do
  d=$HERE/src/$repo
  [ -d "$d/.git" ] || run git clone "https://github.com/vinceliuice/$repo.git" "$d"
  run git -C "$d" checkout -q "${WHITESUR[$repo]}"
done
if [ $DRY = 0 ] && ! git -C "$HERE/src/WhiteSur-gtk-theme" diff --quiet; then
  echo "  Kuro patch already applied"
else
  run git -C "$HERE/src/WhiteSur-gtk-theme" apply "$HERE/patches/whitesur-gtk-kuro.patch"
fi
run bash -c "cd '$HERE/src/WhiteSur-gtk-theme' && ./install.sh -c dark -t red -l"
run bash -c "cd '$HERE/src/WhiteSur-icon-theme' && ./install.sh -t red"
run bash -c "cd '$HERE/src/WhiteSur-cursors' && ./install.sh"

# ------------------------------------------------------------------ 5 art
phase "5/8 fonts, wallpaper and generated art"
run install -Dm644 "$HERE/assets/fonts/Bangers-Regular.ttf" ~/.local/share/fonts/bapirlo/Bangers-Regular.ttf
run install -Dm644 "$HERE/assets/fonts/OFL.txt" ~/.local/share/fonts/bapirlo/OFL.txt
run fc-cache -f ~/.local/share/fonts
run mkdir -p ~/.config/bapirlo
run ln -sfn "$(readlink -f "$WALL")" ~/.config/bapirlo/hero-wallpaper
if [ -n "$CITY" ] && [ -n "$LAT" ] && [ -n "$LON" ]; then
  [ $DRY = 1 ] || printf '{"name": "%s", "lat": %s, "lon": %s}\n' "$CITY" "$LAT" "$LON" > ~/.config/bapirlo/location.json
  echo "  location → ~/.config/bapirlo/location.json"
fi
W=$(python3 -c 'import sys; from PIL import Image; print(Image.open(sys.argv[1]).width)' "$WALL")
if [ "$W" -lt 2560 ] && [ ! -x "$HERE/tools/realesrgan/realesrgan-ncnn-vulkan" ]; then
  echo "  your wallpaper is ${W}px wide. Optional: AI upscale with Real-ESRGAN (anime model, ~45 MB download):"
  echo "    https://github.com/xinntao/Real-ESRGAN/releases → realesrgan-ncnn-vulkan-*-ubuntu.zip → unzip into tools/realesrgan/"
  echo "  without it the picture is resized normally."
fi
run python3 "$HERE/tools/make-hero.py"
run python3 "$HERE/tools/build-desktop-v2.py"
run python3 "$HERE/tools/build-grub-v2.py"
run python3 "$HERE/tools/build-plymouth-v2.py"
run python3 "$HERE/tools/build-lightdm-v2.py"
# Chrome theme new-tab picture (from the hero art, so it is not in the repo either)
run python3 -c "from PIL import Image, ImageEnhance; import os; o='$HERE/apps/chrome-theme/images'; os.makedirs(o, exist_ok=True); \
ImageEnhance.Brightness(Image.open('$HERE/build/art/hero-2560x1600.png').convert('RGB').resize((1920, 1200))).enhance(0.7).save(o + '/ntp.jpg', quality=88)"

# ------------------------------------------------------------------ 6 extensions
phase "6/8 GNOME extensions (extensions.gnome.org, GNOME $GV builds only)"
if [ $DRY = 0 ]; then . "$HERE/lib/ext.sh"; for u in "${ROUND1_EXTS[@]}"; do ext_install "$u"; done
else printf '%s  ext_install %s%s\n' "$D" "${ROUND1_EXTS[*]}" "$N"; fi

# ------------------------------------------------------------------ 7 desktop
phase "7/8 desktop (no sudo)"
run bash "$HERE/10-gnome-settings.sh"
run bash "$HERE/60-desktop-v2.sh" all
run bash "$HERE/70-polish.sh" all
for s in 80-dock-behaviour 85-app-focus 90-workspaces 95-media-widget 100-topbar-extras 105-mac-features \
         110-gsconnect 115-app-themes 120-sound-lock 125-session 210-topbar-v2 220-alive 230-gaming \
         240-daily 250-identity 310-round3; do
  run bash "$HERE/$s.sh"
done

# ------------------------------------------------------------------ 8 boot
if [ $BOOT = 1 ]; then
  phase "8/8 boot: GRUB + Plymouth + LightDM (read 50-boot-v2.sh first — it is written for one machine)"
  run sudo bash "$HERE/50-boot-v2.sh"
  run sudo bash "$HERE/55-grub-tune.sh"
else
  echo; echo "8/8 boot theme skipped (add --boot to include GRUB / Plymouth / LightDM)."
fi

printf '\n%s%sBapirlo OS is installed.%s Log out and back in to load the extensions.\n' "$B" "$R" "$N"
echo "Every step has an undo: bash <script> restore  ·  backups in ~/theme-backups  ·  snapshot \"Before Bapirlo OS\""
